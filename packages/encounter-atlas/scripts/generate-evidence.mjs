import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { sealPackage } from '../src/package.mjs';
import { importRun, inspectRun, renderEpisode, playerView, startEncounter, dispatch } from '../src/encounter.mjs';
import { canonicalJson } from '../src/contracts.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=async name=>JSON.parse(await fs.readFile(path.join(root,name),'utf8'));
const sealed=await sealPackage(await read('content/last-collection.json'));
const saveBytes=await fs.readFile(path.join(root,'M2_Interaction_Run.json'));
const run=await importRun(JSON.parse(saveBytes.toString('utf8')),sealed);
const source=await read('evidence/M2_source_identity.json');
const browserTrace=await read('evidence/M2_Browser_Inspector.json');
const trace=inspectRun(run,sealed);
assert.equal(canonicalJson(browserTrace),canonicalJson(trace),'Browser inspector must match the validated saved run');
assert.equal(run.journal.length,3); assert.equal(run.data.actionResults.length,1);
assert.equal(trace.decisions.length,2); assert.equal(trace.claims.length,1);
const metadata={generator:'scripts/generate-evidence.mjs',origin:'Actual browser UI run exported through Save run',
  runFile:'M2_Interaction_Run.json',runFileSHA256:createHash('sha256').update(saveBytes).digest('hex'),
  sourceRevision:source.sourceRevision,sourceDigest:source.sourceDigest,contentRevision:sealed.content.contentRevision,
  sessionId:run.id,revision:run.revision,packageRef:sealed.ref};
const lines=['# Generated M2 interaction transcript','',
  'Generated by `scripts/generate-evidence.mjs` from the actual browser Save run export. Import validates the exact package and replays the complete command journal before rendering. Dialogue and action details below are implementation output.','',
  `Run: \`${run.id}\`, final revision ${run.revision}. Code: \`${source.sourceRevision}\`. Content: \`${sealed.content.contentRevision}\`.`,
  `Source digest: \`${source.sourceDigest}\`.`,
  `Package: \`${sealed.ref.id}\` revision ${sealed.ref.revision}, SHA-256 \`${sealed.ref.digest}\`.`,
  `Saved run file SHA-256: \`${metadata.runFileSHA256}\`.`,
  'Matching trace: `M2_Inspector_Trace.json`. Browser screenshot: `evidence/M2_Browser_Complete.jpg`.',''];
const block=text=>'```text\n'+text+'\n```';
let replay=await startEncounter(sealed,{runId:run.id,noPressure:run.data.opportunities.noPressure});
for(const entry of run.journal){
  const {command,receipt}=entry;
  lines.push(`## Commit ${receipt.committedRevision}: ${command.kind}`,'',`Command: \`${command.id}\`; prior revision ${command.expectedRevision}.`,'');
  if(command.kind==='send_message'){
    lines.push('Preview bound to this exact submitted command:',block(command.payload.preview.text),'',
      `Canonical sent message: \`${command.payload.preview.message.id}\`. Preview and Send have identical outward communication.`,'');
  }
  const committed=dispatch(replay,sealed,command); assert.equal(committed.status,'committed'); replay=committed.run;
  if(command.kind==='send_message'){
    const episode=renderEpisode(replay,receipt.result.episodeId);
    lines.push('Intake:',block(episode.intake.description),'','Delivery:',block(episode.delivery.description+'\n'+episode.delivery.text),'',
      'Player control is available after Delivery or Skip. Presentation does not execute a second command.','');
    const view=playerView(replay);
    lines.push(`Inspection detail after this commit: ${view.inspectedDetail?JSON.stringify(view.inspectedDetail):'none; permission is not an inspection.'}`,'');
    const decision=trace.decisions.find(d=>d.id===receipt.result.decisionId);
    lines.push(`Decision \`${decision.id}\`: \`${decision.selected}\`. Actual input observations: ${decision.inputObservationIds.map(id=>'`'+id+'`').join(', ')}.`,'');
  }else{
    const result=replay.data.actionResults.find(r=>r.id===receipt.result.resultId);
    lines.push(`Deliberate physical result: \`${result.id}\`, outcome \`${result.outcome}\`, material effects ${JSON.stringify(result.effects)}.`,'');
    for(const observed of result.observerDetails){
      lines.push(`Received by \`${observed.observerId}\`:`,block(JSON.stringify(observed.details,null,2)),'');
    }
    lines.push('The clerk receives visible conduct only. The subsequent report is a separate hearing observation and claim.','');
  }
  lines.push('Committed changes:',block(JSON.stringify(receipt.result.changes,null,2)),'');
}
assert.equal(canonicalJson(replay),canonicalJson(run));
lines.push('## Final causal boundary','',
  `Claims: ${trace.claims.map(c=>'`'+c.id+'` from `'+c.messageId+'`').join(', ')}. Hypotheses: ${trace.hypotheses.length}. Beliefs: ${trace.beliefs.length}.`,
  `Material state: \`${JSON.stringify(trace.materialState)}\`.`,
  'Protected contact value is absent from player observations and listener inputs. The author save/package contains the synthetic fixture value; these files are not player-knowledge projections.',
  'The response offers verification. No recovery, transfer, collection closure, repair or M3 mechanism executes.','');
await fs.writeFile(path.join(root,'M2_Interaction_Transcript.md'),lines.join('\n'));
await fs.writeFile(path.join(root,'M2_Inspector_Trace.json'),JSON.stringify({metadata,trace},null,2)+'\n');
console.log(JSON.stringify({...metadata,messages:trace.canonicalMessages.length,observations:trace.observations.length,claims:trace.claims.length,decisions:trace.decisions.length,validatedReplay:true,browserInspectorMatches:true}));
