import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sealPackage } from '../src/package.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fixture=await sealPackage(JSON.parse(await fs.readFile(path.join(root,'content/last-collection.json'),'utf8')));
await fs.writeFile(path.join(root,'content/last-collection.mjs'),`// Generated by scripts/build.mjs from authored JSON.\nexport const fixture = ${JSON.stringify(fixture,null,2)};\n`);
const visited=new Map(),chunks=[];
async function bundle(file){
  file=path.resolve(file); const name=path.relative(root,file).replaceAll('\\','/'); if(visited.has(name))return name;
  visited.set(name,true); let source=await fs.readFile(file,'utf8');
  const imports=[...source.matchAll(/import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];?/g)];
  for(const match of imports){const dependency=await bundle(path.resolve(path.dirname(file),match[2]));source=source.replace(match[0],`const {${match[1]}} = __modules[${JSON.stringify(dependency)}];`);}
  const exports=[...source.matchAll(/export\s+(?:async\s+)?(?:function|const|let|class)\s+(\w+)/g)].map(m=>m[1]);
  source=source.replace(/\bexport\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/g,'');
  if (/\bimport\s+.*from\s+['"]/.test(source))throw Error('Unsupported import in '+name);
  chunks.push(`__modules[${JSON.stringify(name)}] = (()=>{\n${source}\nreturn {${exports.join(',')}};\n})();`); return name;
}
await bundle(path.join(root,'src/ui.mjs'));
let html=await fs.readFile(path.join(root,'src/shell.html'),'utf8'); const css=await fs.readFile(path.join(root,'src/ui.css'),'utf8');
const script=`(()=>{'use strict';const __modules=Object.create(null);\n${chunks.join('\n')}\n})();`;
html=html.replace('/*APP_CSS*/',css).replace('<!--APP_SCRIPT-->',()=>'<script>'+script.replace(/<\/script/gi,'<\\/script')+'</script>');
await fs.mkdir(path.join(root,'dist'),{recursive:true});await fs.writeFile(path.join(root,'dist/index.html'),html);
console.log(JSON.stringify({build:'dist/index.html',modules:visited.size,bytes:Buffer.byteLength(html),packageRef:fixture.ref}));
